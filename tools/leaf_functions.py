#!/usr/bin/env python3
"""Emit explicit XenonRecomp function boundaries for switch tables in leaf functions.

Leaf functions (no stack frame) have no .pdata entry, and XenonRecomp's analyzer
cuts functions containing jump tables short. For every switch table outside a
.pdata function, bound its function by the nearest `bl` call targets around it
(falling back to the .pdata gap), and verify every case label is inside.

Usage: leaf_functions.py default.pe switch_tables.toml config.toml
Rewrites the block between '# BEGIN leaf functions' and '# END leaf functions'.
"""
import bisect
import re
import sys

sys.path.insert(0, __import__('os').path.dirname(__file__))
import find_switch_tables as fst  # noqa: E402


def call_targets(pe):
    t = set()
    for va, vs in pe.code:
        for o in range(va, va + vs, 4):
            w = pe.w(pe.base + o)
            if w >> 26 == 18 and w & 1:  # bl
                off = w & 0x3FFFFFC
                if off & 0x2000000:
                    off -= 1 << 26
                t.add(pe.base + o + off)
    return sorted(t)


def main(pe_path, switch_path, config_path):
    pe = fst.PE(pe_path)
    sw = open(switch_path).read()
    tables = []
    for block in sw.split('[[switch]]')[1:]:
        base = int(re.search(r'base = 0x([0-9A-F]+)', block).group(1), 16)
        labels = [int(x, 16) for x in re.findall(r'^\s+0x([0-9A-F]+),', block, re.M)]
        tables.append((base, labels))

    starts = [s for s, _ in pe.funcs]
    calls = call_targets(pe)
    funcs = {}
    problems = []
    for base, labels in tables:
        i = bisect.bisect(starts, base)
        if i and pe.funcs[i - 1][0] <= base < pe.funcs[i - 1][1]:
            continue  # inside a .pdata function; XenonRecomp handles it
        gs, ge = pe.funcs[i - 1][1], pe.funcs[i][0]
        while pe.w(gs) == 0:
            gs += 4
        inside = [c for c in calls if gs <= c < ge]
        lo = max([c for c in inside if c <= base] or [gs])
        hi = min([c for c in inside if c > max(labels + [base])] or [ge])
        if not all(lo <= l < hi for l in labels):
            problems.append(base)
            continue
        # trim trailing zero padding
        while hi > lo and pe.w(hi - 4) == 0:
            hi -= 4
        prev = funcs.get(lo)
        funcs[lo] = max(prev or 0, hi)

    lines = ['# BEGIN leaf functions (generated by tools/leaf_functions.py)', 'functions = [']
    for a in sorted(funcs):
        lines.append(f'    {{ address = 0x{a:X}, size = 0x{funcs[a] - a:X} }},')
    lines += [']', '# END leaf functions']
    block = '\n'.join(lines)

    cfg = open(config_path).read()
    pat = re.compile(r'# BEGIN leaf functions.*?# END leaf functions', re.S)
    cfg = pat.sub(block, cfg) if pat.search(cfg) else cfg.rstrip() + '\n\n' + block + '\n'
    open(config_path, 'w').write(cfg)
    print(f'leaf functions written: {len(funcs)}; switches that did not fit: {len(problems)}')
    for p in problems:
        print(f'   0x{p:X}')


if __name__ == '__main__':
    main(*sys.argv[1:4])
