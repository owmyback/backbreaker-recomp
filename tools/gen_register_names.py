#!/usr/bin/env python3
"""Generate runtime/gpu/generated/register_names.cpp from Xenia's register_table.inc.

Usage: gen_register_names.py register_table.inc out.cpp
Source: https://github.com/xenia-project/xenia/blob/master/src/xenia/gpu/register_table.inc
(BSD 3-clause, Copyright Ben Vanik; license in docs/licenses/xenia-LICENSE.txt)
"""
import re
import sys


def main(src, dst):
    regs = []
    for m in re.finditer(r'XE_GPU_REGISTER\(\s*(0x[0-9A-Fa-f]+)\s*,\s*\w+\s*,\s*(\w+)\s*\)', open(src).read()):
        regs.append((int(m.group(1), 16), m.group(2)))
    regs.sort()
    with open(dst, 'w') as f:
        f.write('// Generated by tools/gen_register_names.py from Xenia\'s src/xenia/gpu/register_table.inc\n')
        f.write('// Xenia: Copyright (c) Ben Vanik. BSD 3-clause license, see docs/licenses/xenia-LICENSE.txt\n')
        f.write('#include <cstdint>\n\nnamespace gpu\n{\n')
        f.write('    struct RegisterName { uint32_t index; const char* name; };\n')
        f.write('    extern const RegisterName kRegisterNames[] = {\n')
        for i, n in regs:
            f.write(f'        {{ 0x{i:04X}, "{n}" }},\n')
        f.write('    };\n')
        f.write(f'    extern const uint32_t kRegisterNameCount = {len(regs)};\n}}\n')
    print(f'{len(regs)} register names')


if __name__ == '__main__':
    main(*sys.argv[1:3])
