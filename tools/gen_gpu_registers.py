#!/usr/bin/env python3
"""Generate runtime/gpu/generated/registers.h from Xenia's GPU headers.

Usage: gen_gpu_registers.py registers.h xenos.h register_table.inc out.h

* Every `union alignas(uint32_t) NAME { struct { type field : bits; ... }; }` in registers.h
  becomes a struct with explicit-shift accessors. Each `struct` inside a union is an alternative
  view starting at bit 0; every view must fit in 32 bits and at least one must cover exactly 32,
  and when Xenia annotates a field with `// +N` the computed bit offset must equal N - otherwise
  generation fails.
* Every `enum class` in xenos.h that a register field uses gets a name() function.

Sources: https://github.com/xenia-project/xenia (src/xenia/gpu/registers.h, xenos.h,
register_table.inc), BSD 3-clause, Copyright Ben Vanik - see docs/licenses/xenia-LICENSE.txt.
"""
import re
import sys

FIELD = re.compile(r'^\s*([A-Za-z_][\w:]*)\s+(\w+)\s*:\s*(\d+)\s*;(.*)$')


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return text


def parse_enums(xenos):
    enums = {}
    for m in re.finditer(r'enum class (\w+)\s*(?::\s*[\w:]+)?\s*\{(.*?)\};', strip_comments(xenos), re.S):
        name, body = m.group(1), m.group(2)
        values, nxt = [], 0
        for line in body.split('\n'):
            line = re.sub(r'//.*', '', line).strip().rstrip(',')
            if not line:
                continue
            em = re.match(r'^(k\w+)\s*(?:=\s*(.+))?$', line)
            if not em:
                continue
            ident, expr = em.group(1), em.group(2)
            if expr is not None:
                expr = expr.strip()
                try:
                    val = int(expr, 0)
                except ValueError:
                    prev = dict(values)
                    if expr in prev:
                        val = prev[expr]
                    else:
                        continue  # non-literal expression: skip this entry
            else:
                val = nxt
            values.append((ident, val))
            nxt = val + 1
        enums[name] = values
    return enums


def parse_register_indices(table):
    return {m.group(2): int(m.group(1), 16)
            for m in re.finditer(r'XE_GPU_REGISTER\(\s*(0x[0-9A-Fa-f]+)\s*,\s*\w+\s*,\s*(\w+)\s*\)', table)}


def parse_unions(regs):
    out = []
    for m in re.finditer(r'union alignas\(uint32_t\) (\w+) \{(.*?)\n\};', regs, re.S):
        name, body = m.group(1), m.group(2)
        fields, offset, problems, views = [], 0, [], []
        names = set()
        for line in body.split('\n'):
            if re.match(r'^\s*struct\s*\{', line):
                if offset:
                    views.append(offset)
                offset = 0
                continue
            fm = FIELD.match(line)
            if not fm:
                continue
            ftype, fname, nbits, rest = fm.group(1), fm.group(2), int(fm.group(3)), fm.group(4)
            ann = re.search(r'//\s*\+(\d+)', rest)
            if ann and int(ann.group(1)) != offset:
                problems.append(f'{fname}: computed offset {offset}, Xenia says +{ann.group(1)}')
            if not fname.startswith('_'):
                if fname in names:
                    problems.append(f'duplicate field {fname}')
                names.add(fname)
                fields.append((fname, offset, nbits, ftype))
            offset += nbits
        views.append(offset)
        if any(v > 32 for v in views) or 32 not in views:
            problems.append(f'struct views cover {views} bits (need all <= 32 and one == 32)')
        idx = re.search(r'register_index\s*=\s*XE_GPU_REG_(\w+)', body)
        out.append((name, fields, problems, idx.group(1) if idx else None))
    return out


def main(regs_path, xenos_path, table_path, out_path):
    regs = open(regs_path).read()
    enums = parse_enums(open(xenos_path).read())
    indices = parse_register_indices(open(table_path).read())
    unions = parse_unions(regs)

    bad = [(n, p) for n, _, p, _ in unions if p]
    if bad:
        for n, p in bad:
            print(f'{n}: ' + '; '.join(p), file=sys.stderr)
        sys.exit('register layout check failed')

    used_enums = sorted({t.split('::')[-1] for _, fields, _, _ in unions for _, _, _, t in fields
                         if t.startswith('xenos::') and t.split('::')[-1] in enums})

    o = []
    o.append('// Generated by tools/gen_gpu_registers.py from Xenia\'s src/xenia/gpu/registers.h,')
    o.append('// xenos.h and register_table.inc - do not edit.')
    o.append('// Xenia: Copyright (c) Ben Vanik. BSD 3-clause license, see docs/licenses/xenia-LICENSE.txt')
    o.append('#pragma once')
    o.append('#include <cstdint>\n')
    o.append('namespace gpu::regs\n{')
    o.append('    inline uint32_t field(uint32_t v, uint32_t lo, uint32_t n) { return (v >> lo) & ((1u << n) - 1); }')
    o.append('    inline int32_t sfield(uint32_t v, uint32_t lo, uint32_t n)')
    o.append('    {')
    o.append('        int32_t x = int32_t(field(v, lo, n));')
    o.append('        return (x & (1 << (n - 1))) ? x - (1 << n) : x;')
    o.append('    }\n')
    o.append('    // ---- Enum names (xenos.h) ----')
    for e in used_enums:
        o.append(f'    inline const char* {e}Name(uint32_t v)')
        o.append('    {')
        o.append('        switch (v)')
        o.append('        {')
        seen = set()
        for ident, val in enums[e]:
            if val in seen:
                continue
            seen.add(val)
            label = ident[1:].lstrip('_')  # kFoo -> Foo, k_8_8_8_8 -> 8_8_8_8
            o.append(f'        case {val}: return "{label}";')
        o.append('        default: return "?";')
        o.append('        }')
        o.append('    }')
    o.append('\n    // ---- Register layouts (registers.h) ----')
    for name, fields, _, reg in unions:
        o.append(f'    struct {name}')
        o.append('    {')
        o.append('        uint32_t value;')
        if reg and reg in indices:
            o.append(f'        static constexpr uint32_t kIndex = 0x{indices[reg]:04X};')
        for fname, off, nbits, ftype in fields:
            signed = ftype in ('int32_t', 'int16_t', 'int8_t')
            comment = f'  // {ftype}' if ftype.startswith('xenos::') else ''
            if nbits == 1 and not ftype.startswith('xenos::'):
                o.append(f'        bool {fname}() const {{ return field(value, {off}, 1); }}{comment}')
            elif signed:
                o.append(f'        int32_t {fname}() const {{ return sfield(value, {off}, {nbits}); }}')
            else:
                o.append(f'        uint32_t {fname}() const {{ return field(value, {off}, {nbits}); }}{comment}')
        o.append('    };')
    o.append('}')
    open(out_path, 'w').write('\n'.join(o) + '\n')
    print(f'{len(unions)} register layouts, {len(used_enums)} enums -> {out_path}')


if __name__ == '__main__':
    main(*sys.argv[1:5])
