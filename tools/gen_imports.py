#!/usr/bin/env python3
"""Generate the runtime's kernel import glue from the game's XEX import table.

Writes a C++ file with:
  * a weak stub for every imported function (__imp__Name) that logs the call once and
    returns 0 in r3; real implementations in runtime/kernel/*.cpp override them
  * a table of variable-import slots (address in the image + export name) that the loader
    fills with guest addresses of kernel-owned data
  * a table of function-pointer slots (type-0 records of function exports) that the loader
    points at the matching call thunk

Usage: gen_imports.py default.xex default.pe xboxkrnl_table.inc xam_table.inc out.cpp
"""
import re
import struct
import sys


def load_exports(path):
    out = {}
    for m in re.finditer(r'XE_EXPORT\(\s*\w+\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(\w+)\s*,\s*(\w+)\s*\)', open(path).read()):
        out[int(m.group(1), 16)] = (m.group(2), m.group(3))
    return out


def main(xex_path, pe_path, krnl_inc, xam_inc, out_path):
    x = open(xex_path, 'rb').read()
    pe = open(pe_path, 'rb').read()
    base = 0x82000000
    tables = {'xboxkrnl.exe': load_exports(krnl_inc), 'xam.xex': load_exports(xam_inc)}

    nopt = struct.unpack('>I', x[20:24])[0]
    hdr = dict(struct.unpack('>II', x[24 + 8 * i:32 + 8 * i]) for i in range(nopt))
    il = hdr[0x103FF]
    _size, strsz, nlibs = struct.unpack('>III', x[il:il + 12])
    names, off = [], il + 12
    raw = x[off:off + strsz]
    p = 0
    for _ in range(nlibs):
        e = raw.index(b'\0', p)
        names.append(raw[p:e].decode())
        p = (e + 1 + 3) & ~3

    lib = il + 12 + strsz
    funcs = {}      # name -> thunk address (type 1)
    var_slots = []  # (addr, name, lib)
    fptr_slots = [] # (addr, name)
    unknown = []
    for li in range(nlibs):
        lsize = struct.unpack('>I', x[lib:lib + 4])[0]
        count = struct.unpack('>H', x[lib + 0x26:lib + 0x28])[0]
        table = tables.get(names[li], {})
        for k in range(count):
            addr = struct.unpack('>I', x[lib + 0x28 + 4 * k:lib + 0x2C + 4 * k])[0]
            v = struct.unpack('>I', pe[addr - base:addr - base + 4])[0]
            rtype, ordinal = v >> 24, v & 0xFFFF
            name, kind = table.get(ordinal, (f'{names[li].split(".")[0]}_{ordinal:03X}', 'kFunction'))
            if ordinal not in table:
                unknown.append(name)
            if rtype == 1:
                funcs[name] = addr
            elif kind == 'kVariable':
                var_slots.append((addr, name, names[li]))
            else:
                fptr_slots.append((addr, name))
        lib += lsize

    with open(out_path, 'w') as f:
        f.write('// Generated by tools/gen_imports.py - do not edit\n')
        f.write('#include "kernel/import_support.h"\n\n')
        for name in sorted(funcs):
            f.write(f'PPC_WEAK_IMPORT({name})\n')
        f.write('\nconst ImportFunction g_importFunctions[] = {\n')
        for name in sorted(funcs):
            f.write(f'    {{ 0x{funcs[name]:08X}, "{name}" }},\n')
        f.write('    { 0, nullptr },\n};\n\n')
        f.write('const ImportVariable g_importVariables[] = {\n')
        for addr, name, libname in var_slots:
            f.write(f'    {{ 0x{addr:08X}, "{name}" }},\n')
        f.write('    { 0, nullptr },\n};\n\n')
        f.write('const ImportFunctionPointer g_importFunctionPointers[] = {\n')
        for addr, name in fptr_slots:
            thunk = funcs.get(name, 0)
            f.write(f'    {{ 0x{addr:08X}, 0x{thunk:08X}, "{name}" }},\n')
        f.write('    { 0, 0, nullptr },\n};\n')

    print(f'libraries: {names}')
    print(f'function imports: {len(funcs)}, variable slots: {len(var_slots)}, function-pointer slots: {len(fptr_slots)}')
    print('variables:', ', '.join(sorted({n for _, n, _ in var_slots})))
    if unknown:
        print('unknown ordinals:', unknown)


if __name__ == '__main__':
    main(*sys.argv[1:6])
